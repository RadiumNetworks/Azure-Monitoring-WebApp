    internal static string GetEnglish(string key)
    {
        var value = English.GetString(key, CultureInfo.InvariantCulture);
        return !string.IsNullOrWhiteSpace(value)
            ? value
            : throw new InvalidOperationException($"The English UI resource '{key}' is missing or empty.");
    }

    public static void ValidateEnglish()
    {
        var resources = English.GetResourceSet(CultureInfo.InvariantCulture, true, false)
            ?? throw new InvalidOperationException("The English UI resource file is missing.");
        foreach (DictionaryEntry resource in resources)
            _ = GetEnglish((string)resource.Key);
        foreach (var key in RequiredKeys)
            _ = GetEnglish(key);
        foreach (var entry in QueryTemplateCatalog.Entries)
        {
            _ = GetEnglish(entry.NameResourceKey);
            if (entry.DescriptionResourceKey is { } descriptionKey)
                _ = GetEnglish(descriptionKey);
        }
        foreach (var domain in new[] { "Domain", "NoDomain" })
        foreach (var count in new[] { "One", "Other", "ServiceHealth" })
        foreach (var suppression in new[] { "Counted", "Suppressed" })
        foreach (var outage in new[] { "Normal", "Outage", "Critical" })
        foreach (var heartbeat in new[] { "Current", "Missing" })
            _ = GetEnglish($"Inbox.TargetCell.{domain}.{count}.{suppression}.{outage}.{heartbeat}");
    }
